#!/usr/bin/env python3
"""Write (or check) the list of engine variables this source tree reads.

Usage: gen_env_keys.py [--check] [--root DIR]

Scans src/ for string literals of the form "SUPERROC_...", "LFN_..." or
"LING3_..." and writes them, sorted, to src/cli/serve/recipe_env_keys.inc. The
recipe loader includes that file: a recipe variable that is not on the list is
reported and skipped instead of being exported, so a typo or a setting from
another engine version never passes silently. With --check the file is only
compared and the exit code is 1 when it is out of date.
"""

import pathlib
import re
import sys

LITERAL = re.compile(r'"((?:SUPERROC|LFN|LING3)_[A-Z0-9_]*[A-Z0-9])"')
SUFFIXES = {".c", ".cc", ".cpp", ".h", ".hh", ".hpp", ".hip", ".inc"}
OUTPUT = pathlib.Path("src/cli/serve/recipe_env_keys.inc")
HEADER = (
    "// Generated by tools/recipe/gen_env_keys.py from the string literals in\n"
    "// src/. Do not edit: rerun the tool after adding or removing a variable.\n"
)


def collect(root: pathlib.Path) -> list[str]:
    keys: set[str] = set()
    for path in sorted((root / "src").rglob("*")):
        if path.suffix not in SUFFIXES or not path.is_file():
            continue
        if path.resolve() == (root / OUTPUT).resolve():
            continue
        keys.update(LITERAL.findall(path.read_text(errors="replace")))
    return sorted(keys)


def render(keys: list[str]) -> str:
    return HEADER + "".join(f'"{key}",\n' for key in keys)


def main() -> int:
    args = sys.argv[1:]
    check = "--check" in args
    root = pathlib.Path(__file__).resolve().parents[2]
    if "--root" in args:
        root = pathlib.Path(args[args.index("--root") + 1]).resolve()
    wanted = render(collect(root))
    target = root / OUTPUT
    if check:
        current = target.read_text() if target.is_file() else ""
        if current != wanted:
            print(f"{OUTPUT} is out of date: run tools/recipe/gen_env_keys.py",
                  file=sys.stderr)
            return 1
        return 0
    target.write_text(wanted)
    print(f"wrote {OUTPUT}: {wanted.count(chr(10)) - 2} variables")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
